rows = []
for k, (grp, scale, meth, tool, head, strong) in A.items():
    doi = "10.1002/" + k; w = oa.get(doi, {}); p = px.get(k); c = cr.get(doi, {}); m = em.get(k, {})
    jt = p["jats_type"] if p else ""
    if not p: atype = "UNVERIFIED (no full text)"
    elif p.get("to_editor") or jt == "letter": atype = "Letter"
    elif jt == "article-commentary" and p["n_main_figs"] <= 2 and p["n_refs"] <= 30: atype = "Letter (JATS article-commentary)"
    elif jt == "article-commentary": atype = "Perspective/Commentary"
    else: atype = "Research Article"
    if k == "imt2.70036": atype = "Letter (comment)"
    panels = [x or 1 for x in p["panels"]] if p else []
    rows.append({
        "doi": doi, "title": w.get("title") or c.get("title"), "year": w.get("year"), "article_type": atype, "jats_article_type": jt or "UNVERIFIED",
        "pmcid": m.get("pmcid") or "", "cited_by_openalex_2026-11-24": w.get("cited_by"), "crossref_cited_by": c.get("crossref_citations"),
        "relevance_group": grp, "data_scale": scale, "main_methods": meth,
        "n_main_figures": p["n_main_figs"] if p else "UNVERIFIED", "panels_per_figure_est": ";".join(map(str, panels)) if p else "UNVERIFIED",
        "total_panels_est": sum(panels) if p else "UNVERIFIED",
        "main_text_words_approx": p["main_words"] if p else "UNVERIFIED", "n_refs": p["n_refs"] if p else "UNVERIFIED",
        "tool_or_resource_released": tool, "headline_claim": head, "what_made_it_strong": strong,
        "in_v1_benchmark": "yes" if doi in v1 else "no", "full_text_parsed": "yes" if p else "no",
        "verified_in": "OpenAlex;Crossref" + (";EuropePMC-fullText" if p else ""),
    })
rows.sort(key=lambda r: (r["relevance_group"][0], -(r["cited_by_openalex_2026-11-24"] or 0)))
with open(f"{B}/benchmark_v2.csv", "w", newline="") as f:
    wr = csv.DictWriter(f, fieldnames=list(rows[0])); wr.writeheader(); wr.writerows(rows)
print(len(rows), "rows")
