"""Supporting Information tables v4 -> manuscript/si_tables_v4.md (from result files only)."""
import os, json, numpy as np, pandas as pd
from common_v4 import *
MS = os.path.join(HERE, "..", "..", "..", "..", "manuscript"); R = lambda f: os.path.join(OUT, f)
CTX = {"VincentC_2016": "hospital in-patients", "MetaCardis_2020_a": "metabolic-disease-enriched", "FengQ_2015": "comorbidity-enriched controls",
       "LoombaR_2017": "fatty-liver cohort", "YuJ_2015": "comorbidity-enriched controls", "ThomasAM_2018a": "colonoscopy-referred, comorbidity",
       "BackhedF_2015": "mothers (pregnancy/postpartum)", "YassourM_2018": "mothers", "FerrettiP_2018": "mothers", "ShaoY_2019": "mothers",
       "TettAJ_2019_a": "mothers", "TettAJ_2019_b": "mothers", "TettAJ_2019_c": "mothers", "RaymondF_2016": "antibiotic trial",
       "HMP_2019_ibdmdb": "symptomatic referrals / IBD kindred", "IjazUZ_2017": "IBD kindred", "ZellerG_2014": "colonoscopy-referred",
       "VogtmannE_2016": "colonoscopy-referred", "HanniganGD_2017": "colonoscopy-referred", "CosteaPI_2017": "longitudinal methods set"}
md = lambda df: df.to_markdown(index=False, floatfmt=".3f")
ctry = META.groupby("study_name").country.agg(lambda x: x.mode().iloc[0]); nw = META.groupby("study_name").non_westernized.agg(lambda x: (x == "yes").mean() > .5)
r = pd.read_csv(R("atlas_rows_v4.csv.gz")); H = r[~r.study.str.startswith("TRAIN")]
per = pd.read_csv(R("atlas_perpop_v4.csv")); dev, lock = split()
rows = []
for s in sorted(H.study.unique()):
    g = H[(H.study == s)].drop_duplicates("sample_id"); ps = per[(per.study == s) & (per.model == "lasso")]
    f = lambda d, st: (ps[(ps.disease == d) & (ps.strict == st)].fpr.round(3).tolist() or [None])[0]
    rows.append(dict(cohort=s, country=ctry[s], non_westernised="yes" if nw[s] else "no", split="DEV" if s in dev else "LOCKED",
                     n_full=len(g), n_strict_people=int(g.strict_person.sum()), strict_set="no: " + CTX[s] if s in STRICT_DROP_STUDIES else "yes",
                     FPR_CRC=f("CRC", True) if s not in STRICT_DROP_STUDIES else f("CRC", False), FPR_IBD=f("IBD", True) if s not in STRICT_DROP_STUDIES else f("IBD", False),
                     FPR_T2D=f("T2D", True) if s not in STRICT_DROP_STUDIES else f("T2D", False)))
S1 = pd.DataFrame(rows)
c = json.load(open(R("counts_v4.json"))); dup = pd.read_csv(R("duplicates.csv"))
D = dup.groupby(["sa", "sb"]).agg(pairs=("r", "size"), removed=("removed", lambda x: x.notna().sum()), min_r=("r", "min")).reset_index()
het = pd.read_csv(R("heterogeneity_v4.csv"))[["strict", "disease", "model", "populations", "people", "pooled", "tau", "I2", "pi_lo", "pi_hi", "p10", "p90", "n100_pops", "n100_min", "n100_max", "oob_obs", "oob_exp", "pooled_raw", "pooled_raw_folds"]]
cov = pd.read_csv(R("covariates_v4.csv"))[["strict", "disease", "model", "people", "pops_used", "pops_available", "icc_raw", "icc_spec", "between_var_change_spec", "icc_ext", "between_var_change_ext"]]
hyp = pd.read_csv(R("hypotheses_v4.csv")); tab = pd.read_csv(R("summary_v4_table.csv")); hol = pd.read_csv(R("holm_v4.csv"))
ca = pd.read_csv(R("control_augmentation_v4.csv")); ca["err"] = (ca.fpr - .10).abs()
CA = ca.groupby(["disease", "model", "aug"]).agg(populations=("pop", "size"), mean_abs_err=("err", "mean"), max_fpr=("fpr", "max")).reset_index()
tt = pd.read_csv(R("taxa_top_v4.csv")); ts = pd.read_csv(R("taxa_shift_v4.csv"))
var = pd.read_csv(os.path.join(HERE, "..", "..", "..", "..", "..", "state", "variants_tried.csv"))
ccs = pd.read_csv(R("deploy_v4_cc_summary.csv"))
out = f"""# Supporting Information — tables (v4, generated by code/experiments/atlas/v4/make_si_v4.py)

## Flow of people and cohorts
Healthy adult cohorts with >= 20 controls in curatedMetagenomicData: {len(healthy_studies())} listed; data available for {len(H.study.unique()) + len(dropped_studies())}.
De-duplication removed {c['dedup']['excluded_samples']} samples and dropped {', '.join(c['dedup']['dropped'])} (Table S7).
Full set after de-duplication: {c['full']['people_any']:,} people, {c['full']['populations_any']} cohorts, {c['full']['countries']} countries ({c['full']['non_westernised']} non-westernised).
Strict set (primary): {c['strict']['people_any']:,} people, {c['strict']['populations_any']} cohorts, {c['strict']['countries']} countries ({c['strict']['non_westernised']} non-westernised).
Per classifier, cohorts used to train that classifier are excluded: strict {min(v['pops'] for v in c['strict']['per_classifier'].values())}–{max(v['pops'] for v in c['strict']['per_classifier'].values())} populations.

## Table S1. Healthy cohorts, recruitment context and LASSO FPR (strict set where included, otherwise full set)
{md(S1)}

## Table S2. Between-population heterogeneity (DerSimonian–Laird on logit FPR)
pi_lo/pi_hi: 95% prediction interval; oob_obs/oob_exp: share of populations outside 0.05–0.15 observed / expected under perfect calibration; *_folds: pooled FPR scored with fold models.
{md(het)}

## Table S3. Every fix attempt and variant tried (ledger)
{md(var)}

## Table S4. Burn-in evaluation summary (unit-weighted means; populations = distinct populations)
mad = mean |FPR − 0.10|; p15 = P(FPR > 0.15).
{md(tab)}

## Table S5. Covariate models (as specified: age, sex, BMI, log depth; extended: + Shannon, richness — deviation)
{md(cov)}

## Table S6. Control augmentation (locked populations, de-duplicated)
{md(CA)}

## Table S7. Cross-cohort duplicates (log-profile r > 0.99)
{md(D)}

## Table S8. Taxon decomposition (LASSO, strict set): top contributors in the three most over-flagged populations per test
{md(tt)}

Population-level shifts and oral-taxa share:
{md(ts)}

## Table S9. Pre-specified atlas hypotheses A1–A3, A5 (protocol_atlas.md), de-duplicated data
{md(hyp)}

## Table S10. Holm correction over the 11 population-level P values reported in the main text
{md(hol)}

## Table S11. Contaminated burn-in in locked case–control cohorts
{md(ccs)}
"""
open(os.path.join(MS, "si_tables_v4.md"), "w").write(out); print("written", len(out))
